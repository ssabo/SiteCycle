#!/bin/sh
# Xcode Cloud runs this after cloning, before any build action.
# It records the branch, commit and build time (UTC) in SiteCycleBuildInfo.xcconfig (gitignored), which
# SiteCycleConfig.xcconfig includes. SiteCycle/Info.plist reads the two settings and
# Settings > About shows them. Run it by hand to stamp a local build.
set -eu

REPO_ROOT="${CI_PRIMARY_REPOSITORY_PATH:-$(cd "$(dirname "$0")/.." && pwd)}"

# Xcode Cloud sets CI_BRANCH for branch builds and CI_PULL_REQUEST_SOURCE_BRANCH for PR
# builds; its checkout is a detached HEAD, so git can't name the branch there.
BRANCH="${CI_BRANCH:-${CI_PULL_REQUEST_SOURCE_BRANCH:-}}"
if [ -z "$BRANCH" ] && [ -n "${CI_TAG:-}" ]; then
    BRANCH="tag ${CI_TAG}"
fi
if [ -z "$BRANCH" ]; then
    BRANCH="$(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
fi
COMMIT="${CI_COMMIT:-$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null || true)}"
# ISO 8601 in UTC. The app shows it in the device's time zone.
BUILD_DATE="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

# In an xcconfig, "//" starts a comment and "$(" expands a setting, so keep only safe
# characters and collapse repeated slashes.
sanitize() {
    printf '%s' "$1" | tr -c 'A-Za-z0-9._/ -' '_' | tr -s '/'
}

OUT="$REPO_ROOT/SiteCycleBuildInfo.xcconfig"
{
    echo "// Generated by ci_scripts/ci_post_clone.sh. Do not commit."
    echo "SITECYCLE_GIT_BRANCH = $(sanitize "$BRANCH")"
    echo "SITECYCLE_GIT_COMMIT = $(sanitize "$COMMIT")"
    echo "SITECYCLE_BUILD_DATE = $BUILD_DATE"
} > "$OUT"

echo "Wrote $OUT:"
cat "$OUT"
